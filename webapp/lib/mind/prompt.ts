// ПРОМПТ ЕДИНОГО УМА (Ф4.3) — переписан целиком под новую парадигму.
//
// Три закона этого модуля:
//
// 1. ЦИТИРУЕТ, НЕ ПЕРЕСКАЗЫВАЕТ. Тридцать строк архитектуры читаются из
//    `docs/doctrine/paradigm-architecture.md` НА ВЫПОЛНЕНИИ и входят в промпт
//    дословно. Пересказ доктрины в промпте разъезжается с ней при первой же
//    правке файла — это ровно тот дрейф, который убил старые якоря (компас
//    07-27). Файла нет → громкий отказ, а не тихий промпт без конституции.
//
// 2. МАЛО БЛОКОВ. У старого строителя было ~15 блоков под диспетчера с
//    режимами, вербальными аппрувами и await-детекторами. Здесь четыре:
//    кто ты → конституция → правила предъявления → рабочий контекст.
//    Оркестрация — мышление ума, а не блоки промпта (доктрина §25).
//
// 3. ЧИСТАЯ ФУНКЦИЯ. build получает данные и возвращает строку; IO (чтение
//    доктрины, скиллы, эпизод) — у вызывающего. Промпт проверяется тестами
//    без базы и диска.
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
// D86: карта конвейера ВЫВОДИТСЯ из реестра стадий, а не пересказывается. Второй
// список станций разошёлся бы с первым на первой же правке, и ум учил бы маршрут,
// которого нет, — ровно тот дрейф, который закон №1 этого модуля запрещает для
// доктрины.
import { ROW_DEFINITIONS } from '@/lib/api/pipeline-stages';

export interface MindPromptContext {
  /** Тридцать строк архитектуры — дословно, из файла. Обязательны. */
  doctrine: string;
  /** Серия треда: код и название. Тред без серии — студийный разговор. */
  series?: { code: string; title: string } | null;
  /** Эпизод треда: сессия = эпизод (доктрина §7). */
  episode?: {
    code: string;
    title: string;
    /** Потолок бюджета и потрачено — деньги видны в момент решения. */
    ceiling: number | null;
    spent: number;
  } | null;
  /**
   * Манифесты применимых скиллов (без тел — тела ум читает getSkill'ом).
   * `agents` — из `applies_when.agent`; по нему скилл встаёт на СВОЮ станцию в
   * карте маршрута (пересечение с `ROW_DEFINITIONS[].agents`). Без него скилл
   * попадёт только в общий список и станцию не подсветит.
   */
  skills?: ReadonlyArray<{ slug: string; summary: string; agents?: readonly string[] }>;
  /**
   * Спецификации инструментов реестра (`mindToolSpecs()`). Нужны карте маршрута:
   * из `stations` каждого инструмента выводится «чем проходить эту станцию».
   * Пусто — карта честно скажет «инструмента пока нет», а не умолчит.
   */
  tools?: ReadonlyArray<{ name: string; stations?: readonly string[] }>;
}

/**
 * Читает тридцать строк архитектуры из файла доктрины. Кэш на процесс:
 * конституция меняется коммитом, а не запросом.
 */
let doctrineCache: string | null = null;
export function loadDoctrine(): string {
  if (doctrineCache) return doctrineCache;
  const path = resolve(process.cwd(), '..', 'docs', 'doctrine', 'paradigm-architecture.md');
  const raw = readFileSync(path, 'utf-8'); // нет файла → бросает, и это правильно
  // Дословно строки 1..30 — между первым и последним разделителем `---`.
  const first = raw.indexOf('\n---\n');
  const last = raw.lastIndexOf('\n---\n');
  if (first < 0 || last <= first) {
    throw new Error(`${path}: не нашёл тело доктрины между разделителями --- — формат файла изменился`);
  }
  doctrineCache = raw.slice(first + 5, last).trim();
  return doctrineCache;
}

/** Сбрасывает кэш доктрины (для тестов). */
export function clearDoctrineCache(): void {
  doctrineCache = null;
}

/** Человеческие названия фаз в порядке прохождения. */
const PHASE_TITLES: ReadonlyArray<{ phase: string; title: string }> = [
  { phase: 'pre-production', title: 'ПРЕДПРОДАКШН' },
  { phase: 'production', title: 'ПРОДАКШН' },
  { phase: 'generation', title: 'ГЕНЕРАЦИЯ' },
  { phase: 'distribution', title: 'ДИСТРИБУЦИЯ' },
  { phase: 'analytics', title: 'АНАЛИТИКА' },
];

/**
 * Правила прохождения, которых НЕТ в реестре станций: гейты Директора, пилоты,
 * условия фазы. Авторский текст Директора (редакция 08.08, дословник —
 * `docs/plans/mind-route-director.md`), поэтому написан руками, а не выведен:
 * реестр знает состав конвейера, но не знает, где Директор останавливает работу.
 *
 * Ключи — `id` станции; значение печатается ПОД её строкой. Отдельно `GATE_AFTER`
 * ставит красную черту ПОСЛЕ станции — там ум останавливается и ждёт.
 */
const STATION_NOTES: Readonly<Record<string, string>> = {
  brief: 'слушаешь Директора → предлагаешь ВАРИАНТЫ → он выбирает',
  casting: 'предлагаешь ВАРИАНТЫ каста из канона серии → он выбирает',
  script_critic: 'дорабатываешь; потолок правок — в настройках эпизода, не на глаз',
  episode_references: 'ПИЛОТ: делаешь ПЕРВЫЕ ДВА рефа, не весь набор',
  visual_generator:
    'ПИЛОТ: два ХАРАКТЕРНЫХ шота (по умолчанию первые два, но лучше выбрать показательные)',
  final_cut:
    'ffmpeg с учётом правок длительностей Директора и залитой музыки; ' +
    'у музыки fade 2 сек по умолчанию, переходы — по смыслу или его указанию',
};

/** После этих станций — ЧЕРТА: ум останавливается и ждёт Директора. */
const GATE_AFTER: ReadonlySet<string> = new Set([
  'script_critic',
  'continuity_critic',
  'episode_references',
  'visual_generator',
]);

/** Фазы, которые вообще не начинаются без явного указания в брифе. */
const PHASE_CONDITION: Readonly<Record<string, string>> = {
  distribution:
    'ТОЛЬКО если в брифе сказано, что эпизод выкладывается на канал YouTube. ' +
    'Нет чётких указаний — НЕ ДЕЛАТЬ ВОВСЕ.',
  analytics: 'Та же условность: только при явном указании о публикации.',
};

/**
 * Карта конвейера — ВЫВЕДЕННАЯ из реестра стадий, не пересказанная (D86).
 *
 * Зачем вообще: до 2026-08-08 промпт не содержал ни одной станции. Ум знал, что
 * делает всю работу сам, но не знал, из чего она состоит, — и шёл кратчайшим
 * путём от брифа к картинке. На SS-S20-E04 это дало: кастинг не запрошен,
 * критики не позваны, раскадровка утверждена собой же через три минуты после
 * сценария. Директор: «Писали, писали процесс workflow, но забыли написать о
 * самом процессе». У СТАРОГО консьержа карта в промпте была
 * (`lib/concierge/system-prompt-builder.ts`), новый писался с нуля и её потерял.
 *
 * Почему из реестра, а не строкой: второй список станций разошёлся бы с первым
 * на первой же правке конвейера, и ум учил бы маршрут, которого нет, — ровно тот
 * дрейф, который закон №1 этого модуля запрещает для доктрины.
 *
 * Главное, что карта обязана донести: часть станций — ВХОД ДИРЕКТОРА, а не
 * работа ума. Кастинг не «пропущен» — ум не знал, что его надо ЗАПРОСИТЬ.
 */
function buildRouteBlock(ctx: MindPromptContext): string {
  // Станция → инструменты. Выводится из САМИХ инструментов (`ToolSpec.stations`),
  // поэтому список не может устареть, пока инструмент жив. Пустой `stations`
  // означает «сквозной» — такие перечисляются один раз внизу, а не у каждой станции.
  const toolsByStation = new Map<string, string[]>();
  const crossCutting: string[] = [];
  for (const spec of ctx.tools ?? []) {
    if (!spec.stations || spec.stations.length === 0) {
      crossCutting.push(spec.name);
      continue;
    }
    for (const st of spec.stations) {
      const list = toolsByStation.get(st) ?? [];
      list.push(spec.name);
      toolsByStation.set(st, list);
    }
  }

  // Станция → скиллы. Тоже вывод: у скилла `applies_when.agent`, у станции
  // `agents` — пересечение и есть «ремесло этой станции». Руками ничего не
  // связывается, поэтому новый скилл встаёт на своё место сам.
  const skillsByStation = new Map<string, string[]>();
  for (const s of ctx.skills ?? []) {
    for (const r of ROW_DEFINITIONS) {
      if (!s.agents || s.agents.length === 0) continue;
      if (r.agents.some((a) => s.agents!.includes(a))) {
        const list = skillsByStation.get(r.id) ?? [];
        if (!list.includes(s.slug)) list.push(s.slug);
        skillsByStation.set(r.id, list);
      }
    }
  }

  const lines: string[] = [];
  for (const { phase, title } of PHASE_TITLES) {
    const rows = ROW_DEFINITIONS.filter((r) => r.phase === phase);
    if (rows.length === 0) continue;
    const cond = PHASE_CONDITION[phase];
    lines.push(cond ? `${title} — ${cond}` : `${title}:`);
    for (const r of rows) {
      // `serves` в реестре значит разное по роли: критик СУДИТ станцию, дизайнер
      // ГОТОВИТ для неё план. Одним словом «судит» дизайнер превращался бы во
      // второго критика — карта врала бы в самом месте, ради которого пишется.
      const serves = r.serves
        ? r.role === 'critic'
          ? ` (судит: ${r.serves})`
          : ` (готовит для: ${r.serves})`
        : '';
      const who =
        r.role === 'input'
          ? 'ВХОД ДИРЕКТОРА — просишь и ЖДЁШЬ, сама не делаешь'
          : r.unstaffed
            ? 'станции пока нет — честно скажи, что её нет'
            : `твоя линза: ${r.role}${serves}`;
      lines.push(`  · ${r.label} [${r.id}] — ${who}`);

      const note = STATION_NOTES[r.id];
      if (note) lines.push(`      ${note}`);
      const tools = toolsByStation.get(r.id);
      if (tools?.length) lines.push(`      инструменты: ${tools.join(' · ')}`);
      else if (r.role !== 'input') lines.push('      инструмента ПОКА НЕТ — скажи об этом вслух, не обходи');
      const skills = skillsByStation.get(r.id);
      if (skills?.length) lines.push(`      скиллы (тело — getSkill): ${skills.join(' · ')}`);

      if (GATE_AFTER.has(r.id)) {
        lines.push('  ── ГЕЙТ: зовёшь Директора на утверждение и ЖДЁШЬ ──');
      }
    }
  }

  const cross = crossCutting.length
    ? `\n\nСквозные инструменты (нужны на любой станции): ${crossCutting.join(' · ')}`
    : '';

  return `[МАРШРУТ СТУДИИ — станции конвейера, выведены из реестра]
Ты играешь все линзы сама, но ПОРЯДОК станций — не твой выбор: это поток студии,
а не то, как удобнее или быстрее. Пропуск станции — осознанное решение, названное
ВСЛУХ и обоснованное; молча спрямить маршрут нельзя. Директору нужен не кратчайший
путь к картинке, а пройденный конвейер.

Три вида станций, и разница между ними обязательна к соблюдению:
· ВХОД ДИРЕКТОРА — ты его не производишь, ты его ЗАПРАШИВАЕШЬ и ждёшь ответа.
  Не получила — это стоп и вопрос, а не повод идти дальше без него.
· Твоя работа (author / designer / artist / editor) — делаешь названными инструментами.
· Критик — не отдельное лицо и не помощник, а ТВОЙ второй проход по уже готовому.
  Мера — лист ожиданий, написанный ДО работы, а не «перечитала, нормально»: помня
  замысел, ты дочитываешь в материал то, чего в нём нет. Взвешиваешь: что критично,
  что второстепенно, чем можно пренебречь — и это выносишь Директору на гейте.

${lines.join('\n')}${cross}`;
}

/**
 * Промпт двумя частями под кэш нативного пути (−86% на входных токенах):
 * `stable` не меняется от хода к ходу треда и несёт cache_control;
 * `dynamic` — контекст (деньги, скиллы), меняется и не кэшируется.
 */
export interface MindPromptParts {
  stable: string;
  dynamic: string;
}

export function buildMindPromptParts(ctx: MindPromptContext): MindPromptParts {
  if (!ctx.doctrine.trim()) {
    throw new Error('промпт ума без доктрины не собирается — это конституция, а не украшение');
  }

  const blocks: string[] = [];

  // ── 1. Кто ты ──────────────────────────────────────────────────────────────
  blocks.push(`[КТО ТЫ]
Ты — Полина, единый ум студии SandyStudio. Не диспетчер и не ассистент при
конвейере: маленькие агенты исключены как класс, ВСЮ работу над произведением
делаешь ты сама — инструментами. Ты пишешь сценарий как сценарист, раскладываешь
его как раскадровщик, судишь материал как критик — это ЛИНЗЫ, которые ты
надеваешь и снимаешь, называя вслух («смотрю как сценарист: …»). Собеседник в
этом треде — Директор; отвечай по-русски, телеграфно: вердикт, вещь, точка.`);

  // ── 2. Конституция — дословно ─────────────────────────────────────────────
  blocks.push(`[АРХИТЕКТУРА — 30 СТРОК, ДОСЛОВНО]
${ctx.doctrine}`);

  // ── 2.5. Маршрут ──────────────────────────────────────────────────────────
  // D86 (2026-08-08): промпта КОНВЕЙЕРА тут не было вовсе. Ум знал, что делает
  // всю работу сам, но не знал, из каких станций она состоит, — и шёл
  // кратчайшим путём от брифа к картинке: на SS-S20-E04 кастинг не запрошен,
  // критики не позваны, раскадровка утверждена собой же через три минуты после
  // сценария. Директор: «Писали, писали процесс workflow, но забыли написать о
  // самом процессе». У СТАРОГО консьержа карта в промпте была; новый писался с
  // нуля под доктрину и её не перенёс — тот же класс, что D69/D81.
  blocks.push(buildRouteBlock(ctx));

  // ── 3. Правила предъявления и границы ─────────────────────────────────────
  blocks.push(`[ПРАВИЛА РАБОТЫ — переводы доктрины в действие]
1. «Сделано» — ТОЛЬКО со ссылкой на строку ассета (id + имя файла). Слова
   «показано выше», «текст готов», «я сгенерировала» без предъявленной строки —
   запрещённый класс рапорта (§12). Сомневаешься, предъявлено ли, — предъяви.
2. Длинное изделие (сценарий, раскадровка, плита канона) НИКОГДА не живёт в
   реплике чата. Носитель — ассет: write-asset со статусом DRAFT кладёт версию
   в слот, не вытесняя утверждённую (§15). В реплике — ссылка и краткая суть.
3. Хард-лимиты Директора: публикация · LOCK · бюджет · смена режима (§19).
   Их ты не выполняешь по своей инициативе НИКОГДА — только по прямому слову
   Директора в ЭТОМ треде, и в ответе называешь это слово.
4. Гейты ДО траты (§16): перед платным вызовом (кадр, клип, публикация) называешь
   цену, остаток потолка эпизода и что именно получится. Потолок — решение
   Директора; упёрлась в него — стоп и вопрос, а не тихое урезание работы.
   Цифру остатка берёшь ТОЛЬКО вызовом spend — не подсчётом в уме по собственным
   напечатанным строкам: это ровно тот класс ошибки, который цифру и обесценивает.
5. Отказ громкий и адресный (§14): инструмент упал — показываешь ЕГО текст
   ошибки дословно и что делаешь дальше. Молча повторить или замять — худший
   класс отказа. Три неудачи подряд — стоп и доклад, не четвёртая попытка.
   «Не найдено» — это отказ ТВОЕЙ попытки назвать вещь, а не факт о вещи:
   прежде чем сказать «не существует», проверь другим способом (другой
   \`file_type\`, \`listSeriesBibles\`, \`getEpisode\`) или процитируй отказ и
   спроси. Ошибка поиска, тихо прочитанная как «этого нет», — тот самый
   класс, который правило запрещает.
6. Тред = эпизод (§7). Работаешь только над эпизодом этого треда; чужой сериал —
   чужой тред. Просят чужое — назови нужный тред, не делай здесь.
7. Приёмка — чистотой контекста (§13): свою работу судишь только как автор;
   слепой взгляд заказываешь через blind-brief, и скептику уходят вопросы БЕЗ
   твоих вердиктов.
8. Инструменты — твои руки (§8, §11): реестр выводится из кода (docs/TOOLS.md),
   схемы приходят function-calling'ом. У аргументов-файлов значение
   \`inline:<текст>\` передаёт содержимое строкой. Нужного инструмента нет —
   скажи «инструмента нет», это строка в реестр разрывов, а не повод для обхода.
9. Скиллы — знания оси РАБОТ (§20-21): квот нет, читай сколько нужно ДО работы,
   а не после брака. Тело скилла — getSkill.`);

  const stable = blocks.join('\n\n');

  // ── 4. Рабочий контекст (динамическая часть — не кэшируется) ──────────────
  const lines: string[] = [];
  if (ctx.series) lines.push(`Сериал: ${ctx.series.code} «${ctx.series.title}»`);
  if (ctx.episode) {
    const money =
      ctx.episode.ceiling === null
        ? `потрачено $${ctx.episode.spent.toFixed(2)}, потолок НЕ ЗАДАН — до первой траты получи его у Директора`
        : `потрачено $${ctx.episode.spent.toFixed(2)} из потолка $${ctx.episode.ceiling.toFixed(2)}`;
    lines.push(`Эпизод: ${ctx.episode.code} «${ctx.episode.title}» · ${money}`);
  }
  if (!ctx.series && !ctx.episode) {
    lines.push('Тред студийный: эпизод не привязан. Для работы над эпизодом — его тред.');
  }
  if (ctx.skills?.length) {
    lines.push('', 'Применимые скиллы (тела — через getSkill):');
    for (const s of ctx.skills) lines.push(`- ${s.slug} — ${s.summary}`);
  }
  const dynamic = `[КОНТЕКСТ]
${lines.join('\n')}`;

  return { stable, dynamic };
}

/** Цельный промпт — для тестов и не-кэширующих провайдеров. */
export function buildMindPrompt(ctx: MindPromptContext): string {
  const parts = buildMindPromptParts(ctx);
  return `${parts.stable}\n\n${parts.dynamic}`;
}
