// Правка вида BOTTOM на листе турнаранда S20: навигационные огни зеркальны.
//
// Пункт 12 очереди Полины, найден Директором 12.08. Правка 10.08 меняла огни на
// том же виде и дефект НЕ устранила, а §5 текста плиты объявил его закрытым.
//
// Доказательство без спора о том, где нос: на видах TOP и BOTTOM аппарат развёрнут
// одинаково (нос внизу кадра — там амбер-купол на TOP и днище блистера на BOTTOM).
// Виды сверху и снизу при одной ориентации носа ОБЯЗАНЫ быть зеркальны, а сейчас у
// обоих зелёный слева. TOP верен по §3 (взгляд сверху, нос вниз → правый борт слева),
// значит зеркален BOTTOM.
//
// Метод — ПЕРЕСТАНОВКА КАНАЛОВ R↔G в двух окнах вокруг огней, не перегенерация:
// повтор через провайдер даст другой аппарат (§5 плиты). Для серого корпуса и
// чёрного фона свап каналов — тождественная операция (R≈G), поэтому окно можно
// брать с запасом на гало, ничего вокруг не задев.
import sharp from 'sharp';

const SRC = process.argv[2] ?? '../FILMS/_run/plate/turnaround-v02.png';
const OUT = process.argv[3] ?? '../FILMS/_run/plate/turnaround-v03-candidate.png';

/**
 * Цветной сигнал отделяется от материала ОТНОСИТЕЛЬНОЙ разницей каналов, а не
 * абсолютной. Абсолютный порог ошибается на обоих концах: маленький красит
 * полкорпуса в холодный тон (корпус не строго серый), большой оставляет вокруг
 * огня зелёное кольцо — слабый край гало, где разница мала, но цвет ещё виден.
 * Отношение работает на всей яркости: корпус (150/145) остаётся, край гало
 * (20/40) переставляется.
 */
const RATIO = Number(process.env.FIX_RATIO ?? 0.8);

/**
 * Окна — квадраты ±60 px вокруг центров огней (замер `diag-lights.ts`). Оба края
 * найдены пробой, а не на глаз: рамка в 30 px оставляла за собой хвост старого
 * гало (красное пятно светило из-под нового зелёного огня), а ячейка BOTTOM
 * целиком захватывала тёплое днище блистера и красила его в фиолетовый. Гало
 * укладывается в 60, днище начинается ниже.
 */
const WINDOWS = [
  { x0: 1070, x1: 1190, y0: 579, y1: 699 }, // зелёный слева → станет красным
  { x0: 1288, x1: 1408, y0: 579, y1: 699 }, // красный справа → станет зелёным
];

async function main(): Promise<void> {
  const img = sharp(SRC);
  const { width = 0, height = 0 } = await img.metadata();
  const { data, info } = await img.raw().toBuffer({ resolveWithObject: true });
  const ch = info.channels;

  let touched = 0;
  for (const w of WINDOWS) {
    for (let y = w.y0; y <= w.y1; y += 1) {
      for (let x = w.x0; x <= w.x1; x += 1) {
        const i = (y * width + x) * ch;
        const r = data[i];
        const g = data[i + 1];
        // Свапаем только ЦВЕТНОЙ сигнал — сам огонь и его гало целиком, включая
        // слабый край. Свап «всего, где r≠g» перекрашивал полкорпуса в холодный.
        const hi = Math.max(r, g);
        const lo = Math.min(r, g);
        if (hi < 8 || lo > hi * RATIO) continue;
        data[i] = g;
        data[i + 1] = r;
        touched += 1;
      }
    }
  }

  await sharp(data, { raw: { width, height, channels: ch } })
    .png()
    .toFile(OUT);
  console.log(`переставлено каналов: ${touched} px из ${width * height}`);
  console.log(`кандидат: ${OUT}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
